namespace OfficeEngine.Excel;

/// <summary>The formats of image that a worksheet can hold.</summary>
public enum ExcelImageFormat
{
    /// <summary>Portable Network Graphics.</summary>
    Png = 0,

    /// <summary>Joint Photographic Experts Group.</summary>
    Jpeg = 1,

    /// <summary>Graphics Interchange Format.</summary>
    Gif = 2,

    /// <summary>Windows bitmap.</summary>
    Bmp = 3,

    /// <summary>Tagged Image File Format.</summary>
    Tiff = 4,
}
