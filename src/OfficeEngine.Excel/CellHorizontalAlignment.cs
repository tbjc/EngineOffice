namespace OfficeEngine.Excel;

/// <summary>The horizontal alignment of a cell, mirroring <c>ST_HorizontalAlignment</c>.</summary>
public enum CellHorizontalAlignment
{
    /// <summary>General alignment.</summary>
    General,

    /// <summary>Left alignment.</summary>
    Left,

    /// <summary>Center alignment.</summary>
    Center,

    /// <summary>Right alignment.</summary>
    Right,

    /// <summary>Fill alignment.</summary>
    Fill,

    /// <summary>Justified alignment.</summary>
    Justify,

    /// <summary>Center across the selected cells.</summary>
    CenterContinuous,

    /// <summary>Distributed alignment.</summary>
    Distributed,
}
