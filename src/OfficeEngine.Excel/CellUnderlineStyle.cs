namespace OfficeEngine.Excel;

/// <summary>The underline style of a cell font, mirroring <c>ST_Underline</c>.</summary>
public enum CellUnderlineStyle
{
    /// <summary>No underline.</summary>
    None,

    /// <summary>A single underline.</summary>
    SingleLine,

    /// <summary>A double underline.</summary>
    DoubleLine,

    /// <summary>A single accounting underline.</summary>
    SingleAccounting,

    /// <summary>A double accounting underline.</summary>
    DoubleAccounting,
}
